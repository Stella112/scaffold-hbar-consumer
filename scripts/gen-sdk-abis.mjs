// Regenerates packages/sdk/src/abi.ts from Foundry build output so the SDK never hand-copies ABIs.
// Usage: yarn sdk:abis (after `yarn foundry:compile`)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "packages/foundry/out");
const contracts = ["ConsumerAccount", "ConsumerAccountFactory", "SupraPriceOracle", "SavingsVault", "TokenLaunchpad", "LaunchpadBuyAction"];
const withBytecode = new Set(["ConsumerAccount", "ConsumerAccountFactory", "SupraPriceOracle", "SavingsVault", "TokenLaunchpad", "LaunchpadBuyAction"]);

let src = "// Generated by scripts/gen-sdk-abis.mjs from packages/foundry/out. Do not edit by hand.\n\n";
for (const name of contracts) {
  const file = path.join(out, `${name}.sol`, `${name}.json`);
  if (!fs.existsSync(file)) {
    console.error(`missing ${file}; run \`yarn foundry:compile\` first`);
    process.exit(1);
  }
  const { abi, bytecode } = JSON.parse(fs.readFileSync(file, "utf8"));
  const id = name[0].toLowerCase() + name.slice(1);
  src += `export const ${id}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
  if (withBytecode.has(name)) {
    src += `export const ${id}Bytecode = ${JSON.stringify(bytecode.object)} as const;\n\n`;
  }
}
fs.writeFileSync(path.join(root, "packages/sdk/src/abi.ts"), src);
console.log("wrote packages/sdk/src/abi.ts");
